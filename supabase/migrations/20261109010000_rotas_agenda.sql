-- 1. ROTA FIXA (criada pelo admin; repete nos dias da semana escolhidos)
create table if not exists public.rota (
  id            bigint generated by default as identity primary key,
  nome          text not null unique,
  escola        text not null default '',
  horario       time not null default '18:00',
  tipo          text not null default 'ida',          -- 'ida' | 'volta'
  dias_semana   text not null default '1,2,3,4,5',    -- 0=domingo ... 6=sábado
  motorista_cpf text,
  veiculo_placa text,
  ativo         boolean not null default true,
  criado_em     timestamptz not null default now()
);

-- 2. PARADAS DA ROTA FIXA
create table if not exists public.rota_parada (
  id        bigint generated by default as identity primary key,
  rota_id   bigint not null references public.rota(id) on delete cascade,
  ordem     int not null,
  nome      text not null,
  endereco  text not null default '',
  latitude  numeric(10,7) not null,
  longitude numeric(10,7) not null
);
create index if not exists rota_parada_rota_idx on public.rota_parada(rota_id, ordem);

-- 3. EM QUAL ROTA CADA ALUNO ESTÁ (um aluno = uma rota)
create table if not exists public.aluno_rota (
  aluno_cpf text primary key,
  rota_id   bigint not null references public.rota(id) on delete cascade
);

-- 4. A viagem do dia passa a apontar para a rota fixa
alter table public.viagem add column if not exists rota_id bigint references public.rota(id) on delete set null;

-- 5. Traz a rota que já existe hoje (viagem 1) para a tabela de rotas fixas
insert into public.rota (nome, escola, horario, tipo, motorista_cpf, veiculo_placa)
select distinct on (v.nome_rota) v.nome_rota, 'Faculdade Maurício de Nassau', v.horario, lower(v.tipo), v.motorista_cpf, v.veiculo_placa
  from public.viagem v
 where v.nome_rota is not null
 order by v.nome_rota, v.data desc
on conflict (nome) do nothing;

insert into public.rota_parada (rota_id, ordem, nome, latitude, longitude)
select r.id, p.ordem, p.nome, p.latitude, p.longitude
  from public.rota r
  join lateral (
    select v.id from public.viagem v where v.nome_rota = r.nome order by v.data desc limit 1
  ) ult on true
  join public.parada p on p.viagem_id = ult.id
 where not exists (select 1 from public.rota_parada rp where rp.rota_id = r.id);

-- Alunos aprovados que ainda não têm rota ficam na rota que já usavam (Linha 01)
insert into public.aluno_rota (aluno_cpf, rota_id)
select a.cpf, (select id from public.rota order by id limit 1)
  from public.aluno a
 where upper(coalesce(a.status, '')) = 'APROVADO'
   and exists (select 1 from public.rota)
on conflict (aluno_cpf) do nothing;

update public.viagem v set rota_id = r.id
  from public.rota r
 where v.rota_id is null and v.nome_rota = r.nome;

-- 5b. ÚLTIMA POSIÇÃO GPS DO ÔNIBUS (motorista envia, alunos veem no mapa)
create table if not exists public.viagem_gps (
  viagem_id     bigint primary key references public.viagem(id) on delete cascade,
  latitude      numeric(10,7) not null,
  longitude     numeric(10,7) not null,
  atualizado_em timestamptz not null default now()
);

-- 6. VIAGEM DO DIA: devolve (ou cria) a viagem de hoje de uma rota,
--    copiando as paradas. Não cria nada em feriado ou em dia sem rota.
create or replace function public.viagem_do_dia(p_rota_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_hoje  date := (now() at time zone 'America/Recife')::date;
  v_dow   text := extract(dow from v_hoje)::int::text;
  v_rota  public.rota%rowtype;
  v_viag  public.viagem%rowtype;
  v_feriado text;
begin
  select * into v_rota from public.rota where id = p_rota_id and ativo;
  if v_rota.id is null then
    return jsonb_build_object('resultado', 'sem_rota');
  end if;

  select nome into v_feriado from public.feriado where data = v_hoje limit 1;
  if v_feriado is not null then
    return jsonb_build_object('resultado', 'feriado', 'feriado', v_feriado);
  end if;

  select * into v_viag from public.viagem
   where rota_id = v_rota.id and data = v_hoje
   order by id limit 1;

  if v_viag.id is null then
    if not (v_dow = any (string_to_array(replace(v_rota.dias_semana, ' ', ''), ','))) then
      return jsonb_build_object('resultado', 'sem_viagem_hoje');
    end if;

    insert into public.viagem (data, horario, nome_rota, tipo, motorista_cpf, veiculo_placa, status, rota_id)
    values (
      v_hoje,
      v_rota.horario,
      v_rota.nome,
      v_rota.tipo,
      coalesce(v_rota.motorista_cpf, (select cpf from public.motorista order by cpf limit 1)),
      coalesce(v_rota.veiculo_placa, (select placa from public.veiculo order by placa limit 1)),
      'AGENDADA',
      v_rota.id
    )
    returning * into v_viag;

    insert into public.parada (viagem_id, ordem, nome, latitude, longitude)
    select v_viag.id, rp.ordem, rp.nome, rp.latitude, rp.longitude
      from public.rota_parada rp
     where rp.rota_id = v_rota.id
     order by rp.ordem;
  end if;

  return jsonb_build_object('resultado', 'ok', 'viagem', to_jsonb(v_viag));
end;
$$;

revoke all on function public.viagem_do_dia(bigint) from public;
grant execute on function public.viagem_do_dia(bigint) to anon, authenticated;

-- 7. PERMISSÕES para o app (chave pública)
grant select, insert, update, delete on public.rota, public.rota_parada, public.aluno_rota, public.viagem_gps to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
grant select, insert, update, delete on public.aviso, public.feriado, public.presenca to anon, authenticated;
grant select, insert, update on public.viagem, public.parada to anon, authenticated;
grant select on public.veiculo to anon, authenticated;
grant insert on public.veiculo to anon, authenticated;

-- Cadastro de aluno pelo app (a senha é criptografada pelo gatilho hash_senha_trigger)
grant insert (cpf, nome_completo, numero_celular, senha, cidade_id, faculdade_id, status) on public.aluno to anon, authenticated;
-- Admin: aprovar/recusar e editar dados (nunca a senha)
grant update (nome_completo, numero_celular, cidade_id, faculdade_id, status, motivo_recusa) on public.aluno to anon, authenticated;
-- Admin: cadastrar motorista
grant insert (cpf, nome_completo, email, numero_celular, senha, carteira_conducao, cidade_id) on public.motorista to anon, authenticated;
grant update (nome_completo, email, numero_celular, cidade_id) on public.motorista to anon, authenticated;

-- RLS liberada para o app nas tabelas que ele usa
do $$
declare t text;
begin
  foreach t in array array['rota','rota_parada','aluno_rota','viagem_gps','aviso','feriado','presenca','viagem','parada','aluno','motorista','veiculo'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists app_acesso on public.%I', t);
    execute format('create policy app_acesso on public.%I for all to anon, authenticated using (true) with check (true)', t);
  end loop;
end;
$$;

